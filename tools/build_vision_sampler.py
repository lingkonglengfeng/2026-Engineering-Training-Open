"""Build a standalone sampler using the exact production CAM1 lamp driver."""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    production = (ROOT / 'vision/maixcam_service/service.py').read_text(encoding='utf-8')
    light = production.split('# LIGHT_GPIO_BEGIN', 1)[1].split('# LIGHT_GPIO_END', 1)[0].strip()
    camera = next(node for node in ast.parse(production).body if isinstance(node, ast.Assign)
                  and ast.unparse(node.targets[0]) == '(CAPTURE_WIDTH, CAPTURE_HEIGHT, CAPTURE_FPS)')
    source = (ROOT / 'vision/maixcam_sampler/sampler.py').read_text(encoding='utf-8')
    source = source.replace('# LIGHT_DRIVER_INSERT', light).replace('# CAMERA_CONFIG_INSERT', ast.get_source_segment(production, camera))
    compile(source, '<sampler>', 'exec')
    target = ROOT / 'vision/maixcam_sampler/main.py'
    target.write_text('# Generated by tools/build_vision_sampler.py\n' + source, encoding='utf-8')
    return target


if __name__ == '__main__':
    print(build())
