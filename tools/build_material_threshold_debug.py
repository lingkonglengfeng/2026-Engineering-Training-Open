"""Bundle the production material detector into a single MaixVision debug app."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MATERIAL = ROOT / "vision/maixcam_material/main.py"
TEMPLATE = ROOT / "vision/maixcam_material/_threshold_debug_app.py"
OUTPUT = ROOT / "vision/maixcam_material/material_threshold_debug.py"


def build():
    source = MATERIAL.read_text(encoding="utf-8")
    template = TEMPLATE.read_text(encoding="utf-8")
    assert template.count('_BUNDLED_MATERIAL = ""') == 1
    bundled = template.replace('_BUNDLED_MATERIAL = ""',
                               '_BUNDLED_MATERIAL = ' + repr(source), 1)
    OUTPUT.write_text("# Generated by tools/build_material_threshold_debug.py; edit _threshold_debug_app.py\n"
                      + bundled, encoding="utf-8")
    return OUTPUT


if __name__ == "__main__":
    print(build())
