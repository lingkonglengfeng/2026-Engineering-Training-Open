"""生成MaixVision可直接上传的统一服务单文件；不在设备启动三个子进程。"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DETECTORS = {"material": "vision/maixcam_material/main.py", "plate": "vision/maixcam_material/plate_tangent.py",
             "ring": "vision/maixcam_ring/middle_ring.py"}


def build():
    source = (ROOT / "vision/maixcam_service/service.py").read_text(encoding="utf-8")
    bundled = {name: (ROOT / path).read_text(encoding="utf-8") for name, path in DETECTORS.items()}
    source = source.replace('_BUNDLED_DETECTORS = {}', '_BUNDLED_DETECTORS = ' + repr(bundled), 1)
    protocol = (ROOT / "vision/protocol8.py").read_text(encoding="utf-8").split("\n", 1)[1]
    source = source.replace('from protocol8 import crc8, make_frame, encode_pixel_frame, MAT_PX, RING_PX, PLATE_PX',
                            '# Embedded project protocol8\n' + protocol.strip(), 1)
    destination = ROOT / "vision/maixcam_service/main.py"
    destination.write_text('# Generated by tools/build_vision_service.py; edit service.py\n' + source, encoding="utf-8")
    return destination


if __name__ == "__main__":
    print(build())
