"""Bundle the shared envelope module for a single-file MaixVision upload."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]


def build(role="material"):
    if role not in ('material','qr'):raise ValueError('Unknown bridge role')
    wire = (ROOT / "vision/pc_vision/wire.py").read_text(encoding="utf-8")
    source = (ROOT / "vision/maixcam_bridge/bridge.py").read_text(encoding="utf-8")
    source = "\n".join(line for line in source.splitlines() if not line.startswith("from pc_wire import "))
    source=source.replace('BRIDGE_ROLE = "material"','BRIDGE_ROLE = '+repr(role))
    folder=ROOT/('vision/maixcam_qr_bridge' if role=='qr' else 'vision/maixcam_bridge')
    folder.mkdir(parents=True,exist_ok=True)
    destination = folder/'main.py'
    destination.write_text("# Generated by tools/build_pc_vision_bridge.py\n" + wire + "\n\n" + source + "\n", encoding="utf-8")
    return destination


if __name__ == "__main__":
    parser=argparse.ArgumentParser();parser.add_argument('--camera',choices=('material','qr','all'),default='material')
    args=parser.parse_args()
    for role in (('material','qr') if args.camera=='all' else (args.camera,)):print(build(role))
