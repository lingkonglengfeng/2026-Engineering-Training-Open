"""将CAM2扫码与协议嵌入一个main.py；无需上传CAM1算法/灯控文件。"""
from pathlib import Path
from zipfile import ZipFile

ROOT=Path(__file__).resolve().parents[1]


def build():
    source=(ROOT/'vision/maixcam_qr/service.py').read_text(encoding='utf-8')
    protocol=(ROOT/'vision/protocol8.py').read_text(encoding='utf-8').split('\n',1)[1].strip()
    source=source.replace('from protocol8 import crc8, make_frame, PROTOCOL_COLOR_IDS',protocol,1)
    target=ROOT/'vision/maixcam_qr/main.py'
    generated='# Generated by tools/build_qr_service.py; edit service.py\n'+source
    metadata=(ROOT/'vision/maixcam_qr/app.yaml').read_text(encoding='utf-8')
    if 'version: 1.0.3' in metadata.splitlines():
        # Frozen release has historical CRCRLF endings. Preserve its exact bytes;
        # source/protocol equivalence must still hold, so never hide source edits.
        with ZipFile(ROOT/'vision/maixcam_qr/dist/maix-cam2_qr-v1.0.3.zip') as archive:
            frozen=archive.read('main.py')
        normalize=lambda text:text.replace('\r\r\n','\n').replace('\r\n','\n')
        if normalize(generated)!=normalize(frozen.decode('utf-8')):
            raise ValueError('Frozen1.0.3 source mismatch; bump version before modifying this release')
        target.write_bytes(frozen)
    else:
        target.write_text(generated,encoding='utf-8')
    return target


if __name__=='__main__':print(build())
